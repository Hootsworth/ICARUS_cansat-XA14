@pages_router.get("/admin", response_class=HTMLResponse)
async def admin_page(request: Request):
    if not is_admin(request):
        return templates.TemplateResponse("admin_login.html", {"request": request, "error": None})
        
    conn = get_db_connection()
    cur = conn.cursor()
    cur.execute("SELECT * FROM teams ORDER BY id ASC")
    teams = [dict(t) for t in cur.fetchall()]
    
    cur.execute("SELECT * FROM app_state")
    app_state = {r["key"]: r["value"] for r in cur.fetchall()}
    
    # 1. Fetch round statuses across all 4 rounds
    cur.execute("SELECT * FROM round_status")
    all_round_statuses = cur.fetchall()
    # Map: (team_id, round_id) -> row dict
    team_rounds = {}
    for rs in all_round_statuses:
        team_rounds[(rs["team_id"], rs["round_id"])] = dict(rs)
        
    # 2. Fetch Round 3 Game Sessions (secret scores)
    cur.execute("SELECT * FROM game_sessions ORDER BY id DESC")
    game_sessions = [dict(g) for g in cur.fetchall()]
    
    # 3. Fetch Round 4 Solves per team
    cur.execute("SELECT team_id, COUNT(*) as solves, SUM(points_awarded) as r4_pts FROM submissions WHERE correct = 1 GROUP BY team_id")
    r4_solves_map = {row["team_id"]: (row["solves"], row["r4_pts"] or 0) for row in cur.fetchall()}
    
    # Compile Master Team Overview
    team_overview = []
    for tm in teams:
        tid = tm["id"]
        r1_info = team_rounds.get((tid, 1), {"status": "active", "score": 0, "submitted_at": None})
        r2_info = team_rounds.get((tid, 2), {"status": "locked", "score": 0, "submitted_at": None})
        r3_info = team_rounds.get((tid, 3), {"status": "locked", "score": 0, "submitted_at": None})
        r4_solves, r4_pts = r4_solves_map.get(tid, (0, 0))
        
        r1_score = r1_info["score"] if r1_info["status"] == "submitted" else 0
        r2_score = r2_info["score"] if r2_info["status"] == "submitted" else 0
        r3_score = r3_info["score"] if r3_info["status"] == "submitted" else 0
        
        grand_total = r1_score + r2_score + r3_score + r4_pts
        public_total = r1_score + r2_score + r4_pts
        
        team_overview.append({
            "team": tm,
            "r1": r1_info,
            "r2": r2_info,
            "r3": r3_info,
            "r4_solves": r4_solves,
            "r4_pts": r4_pts,
            "grand_total": grand_total,
            "public_total": public_total
        })
        
    # Sort teams by Grand Total descending
    team_overview.sort(key=lambda x: -x["grand_total"])

    # 4. Fetch Security & Timing Events
    cur.execute("SELECT * FROM events ORDER BY ts_utc_ms DESC LIMIT 40")
    recent_events = [dict(e) for e in cur.fetchall()]
    
    # 5. Fetch Recent Submissions
    cur.execute("SELECT * FROM submissions ORDER BY ts_utc_ms DESC LIMIT 30")
    recent_subs = [dict(s) for s in cur.fetchall()]
    
    conn.close()
    
    return templates.TemplateResponse("admin.html", {
        "request": request,
        "teams": teams,
        "team_overview": team_overview,
        "app_state": app_state,
        "recent_subs": recent_subs,
        "game_sessions": game_sessions,
        "recent_events": recent_events
    })

