@pages_router.get("/dashboard", response_class=HTMLResponse)
async def dashboard_page(request: Request):
    team = get_session_team(request)
    if not team:
        return RedirectResponse(url="/login", status_code=302)
        
    conn = get_db_connection()
    cur = conn.cursor()
    
    # Fetch team credits
    cur.execute("SELECT credits FROM teams WHERE id = ?", (team["id"],))
    credits = cur.fetchone()["credits"]
    
    # Fetch all challenges
    cur.execute("SELECT * FROM challenges WHERE round_id IN (2, 4) ORDER BY order_num ASC")
    challenges = [dict(c) for c in cur.fetchall()]
    
    # Fetch team solves
    cur.execute("SELECT * FROM submissions WHERE team_id = ? AND correct = 1", (team["id"],))
    solves = {s["challenge_id"]: dict(s) for s in cur.fetchall()}
    
    # Fetch team flags
    cur.execute("SELECT * FROM flags WHERE team_id = ?", (team["id"],))
    flags = {f["phase"]: f["flag"] for f in cur.fetchall()}
    
    # App states
    cur.execute("SELECT * FROM app_state")
    app_state = {r["key"]: r["value"] for r in cur.fetchall()}
    
    # Fetch Round Statuses for all 4 Rounds
    cur.execute("SELECT round_id, status, score, unlocked_at, submitted_at FROM round_status WHERE team_id = ?", (team["id"],))
    raw_round_statuses = {r["round_id"]: dict(r) for r in cur.fetchall()}
    
    conn.close()
    
    # Round 4 retains only its live finale. Round 2 owns the telemetry investigation.
    phases = {
        "FINALE": {"title": "Phase 4: Live Contingency Finale", "desc": "Real-time state machine anomaly recovery using the flight runbook.", "challenges": []}
    }

    for ch in challenges:
        ch["is_solved"] = (ch["id"] in solves)
        ch["points_awarded"] = solves[ch["id"]]["points_awarded"] if ch["is_solved"] else 0
        if ch["round_id"] == 4 and ch["phase"] in phases:
            phases[ch["phase"]]["challenges"].append(ch)
            
    round4_score = sum(s["points_awarded"] for s in solves.values() if any(ch["id"] == s["challenge_id"] and ch["round_id"] == 4 for ch in challenges))
    
    # Establish defaults for each round
    rounds_summary = {}
    for rid in [1, 2, 3, 4]:
        st = raw_round_statuses.get(rid, {"status": "locked", "score": 0, "unlocked_at": None, "submitted_at": None})
        rounds_summary[rid] = st
        
    # Round 1 default is active if not set
    if rounds_summary[1]["status"] == "locked":
        rounds_summary[1]["status"] = "active"
        
    # Check unlock progression with overrides
    if (rounds_summary[1]["status"] == "submitted" or app_state.get("round2_active") == "true") and rounds_summary[2]["status"] == "locked":
        rounds_summary[2]["status"] = "active"
        
    if (rounds_summary[2]["status"] == "submitted" or app_state.get("round3_active") == "true") and rounds_summary[3]["status"] == "locked":
        rounds_summary[3]["status"] = "active"
        
    if (rounds_summary[3]["status"] == "submitted" or app_state.get("round4_active") == "true") and rounds_summary[4]["status"] == "locked":
        rounds_summary[4]["status"] = "active"
        
    rounds_summary[4]["score"] = round4_score
    if round4_score > 0 and rounds_summary[4]["status"] != "submitted":
        rounds_summary[4]["status"] = "active"

    # CRITICAL: Strip Round 3 raw score so it CANNOT be leaked to team client/DOM
    rounds_summary[3].pop("score", None)
    
    # Total visible score aggregates Rounds 1 + 2 + 4 only
    r1_score = rounds_summary[1]["score"] if rounds_summary[1]["status"] == "submitted" else 0
    r2_score = rounds_summary[2]["score"] if rounds_summary[2]["status"] == "submitted" else 0
    total_score = r1_score + r2_score + round4_score
    
    return templates.TemplateResponse("dashboard.html", {
        "request": request,
        "team": team,
        "credits": credits,
        "phases": phases,
        "flags": flags,
        "rounds_summary": rounds_summary,
        "r1_score": r1_score,
        "r2_score": r2_score,
        "r4_score": round4_score,
        "total_score": total_score,
        "app_state": app_state,
        "mission_name": MISSION_NAME
    })

@pages_router.get("/challenge/{challenge_id}", response_class=HTMLResponse)
async def challenge_detail_page(request: Request, challenge_id: str):
    team = get_session_team(request)
    if not team:
        return RedirectResponse(url="/login", status_code=302)
        
    conn = get_db_connection()
    cur = conn.cursor()
    
    cur.execute("SELECT * FROM challenges WHERE id = ?", (challenge_id.upper(),))
    ch = cur.fetchone()
    if not ch:
        conn.close()
        raise HTTPException(status_code=404, detail="Challenge not found.")
        
    if ch["round_id"] == 2 and ch["phase"] in ("PHASE_2", "PHASE_3"):
        required_phase = "PHASE_1" if ch["phase"] == "PHASE_2" else "PHASE_2"
        cur.execute("SELECT 1 FROM flags WHERE team_id = ? AND phase = ?", (team["id"], required_phase))
        if not cur.fetchone():
            conn.close()
            return RedirectResponse(url="/round2", status_code=302)

    cur.execute("SELECT * FROM submissions WHERE team_id = ? AND challenge_id = ? ORDER BY ts_utc_ms DESC", (team["id"], ch["id"]))
    submissions = [dict(s) for s in cur.fetchall()]
    
    is_solved = any(s["correct"] == 1 for s in submissions)
    solved_sub = next((s for s in submissions if s["correct"] == 1), None)
    
    # Calculate cooldown
    wrong_count = len(submissions) if not is_solved else 0
    in_cooldown = False
    cooldown_rem = 0
    if wrong_count >= 5 and not is_solved:
        last_ts = submissions[0]["ts_utc_ms"]
        elapsed = (int(time.time() * 1000) - last_ts) / 1000.0
        if elapsed < 600:
            in_cooldown = True
            cooldown_rem = int(600 - elapsed)
            
    conn.close()
    
    return templates.TemplateResponse("challenge.html", {
        "request": request,
        "team": team,
        "challenge": dict(ch),
        "submissions": submissions,
        "is_solved": is_solved,
        "solved_sub": solved_sub,
        "in_cooldown": in_cooldown,
        "cooldown_rem": cooldown_rem
    })

