@pages_router.post("/admin/action")
async def admin_action(request: Request, action: str = Form(...), team_id: int = Form(None), val: str = Form(None)):
    if not is_admin(request):
        raise HTTPException(status_code=401, detail="Admin authorization required.")
        
    conn = get_db_connection()
    cur = conn.cursor()
    
    if action == "freeze_scoreboard":
        cur.execute("UPDATE app_state SET value = 'true' WHERE key = 'scoreboard_frozen'")
    elif action == "unfreeze_scoreboard":
        cur.execute("UPDATE app_state SET value = 'false' WHERE key = 'scoreboard_frozen'")
    elif action == "release_errata":
        cur.execute("UPDATE app_state SET value = 'true' WHERE key = 'errata_released'")
    elif action == "start_finale":
        cur.execute("UPDATE app_state SET value = 'true' WHERE key = 'finale_started'")
    elif action == "toggle_round" and val:
        # Toggle round active state (e.g. round2_active)
        cur.execute("SELECT value FROM app_state WHERE key = ?", (val,))
        row = cur.fetchone()
        new_val = "false" if (row and row["value"] == "true") else "true"
        cur.execute("INSERT OR REPLACE INTO app_state (key, value) VALUES (?, ?)", (val, new_val))
    elif action == "adjust_credits" and team_id is not None and val:
        credits_delta = int(val)
        cur.execute("UPDATE teams SET credits = credits + ? WHERE id = ?", (credits_delta, team_id))
    elif action == "reset_cooldown" and team_id is not None:
        cur.execute("DELETE FROM submissions WHERE team_id = ? AND correct = 0", (team_id,))
    elif action == "unlock_round" and team_id is not None and val:
        round_to_unlock = int(val)
        cur.execute("""
        INSERT OR REPLACE INTO round_status (team_id, round_id, status, score, unlocked_at)
        VALUES (?, ?, 'active', 0, ?)
        """, (team_id, round_to_unlock, datetime.now(timezone.utc).isoformat()))
        
    conn.commit()
    conn.close()
    return RedirectResponse(url="/admin", status_code=302)
