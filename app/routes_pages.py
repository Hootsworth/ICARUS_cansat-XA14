@pages_router.post("/register", response_class=HTMLResponse)
async def register_submit(
    request: Request,
    team_id: int = Form(...),
    team_name: str = Form(...),
    password: str = Form(...),
    join_code: str = Form(...)
):
    if join_code.strip() != EVENT_JOIN_CODE:
        return templates.TemplateResponse("register.html", {"request": request, "error": "Invalid Event Join Code. Check your briefing sheet."})
        
    if team_id < 1 or team_id > TOTAL_TEAMS:
        return templates.TemplateResponse("register.html", {"request": request, "error": f"Team ID must be between 1 and {TOTAL_TEAMS}."})
        
    # Read generated metadata
    answers_file = os.path.join(ANSWERS_DIR, "master_answers.json")
    if not os.path.exists(answers_file):
        return templates.TemplateResponse("register.html", {"request": request, "error": "Competition data not yet generated by flight director."})
        
    with open(answers_file, "r", encoding="utf-8") as f:
        master_answers = json.load(f)
        
    team_data = master_answers.get(str(team_id))
    if not team_data:
        return templates.TemplateResponse("register.html", {"request": request, "error": f"Team {team_id} not found in master configuration."})
        
    conn = get_db_connection()
    cur = conn.cursor()
    
    cur.execute("SELECT * FROM teams WHERE id = ? OR name = ?", (team_id, team_name.strip()))
    if cur.fetchone():
        conn.close()
        return templates.TemplateResponse("register.html", {"request": request, "error": f"Team {team_id} or Team Name '{team_name}' is already registered."})
        
    pw_hash = hash_password(password)
    cur.execute("""
    INSERT INTO teams (id, name, pw_hash, seed, credits, api_token, launch_auth_code, created_at)
    VALUES (?, ?, ?, ?, 12, ?, ?, ?)
    """, (team_id, team_name.strip(), pw_hash, team_data["seed"], team_data["api_token"], team_data["launch_auth_code"], datetime.now(timezone.utc).isoformat()))
    
    conn.commit()
    conn.close()
    
    request.session["team_id"] = team_id
    request.session["team_name"] = team_name.strip()
    return RedirectResponse(url="/dashboard", status_code=302)

